  await expect(page.getByRole("heading",{name:"我的项目",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"幻灯片",exact:true}).click();
  await expect(page.locator(".studio-project")).toHaveCount(1);
  await page.getByRole("button",{name:"视频",exact:true}).click();
  await expect(page.getByText("没有匹配的项目", {exact:true})).toBeVisible();

  await nav(page).getByRole("link",{name:"首页",exact:true}).click();
  await expect(prompt(page)).toBeEmpty();
  await prompt(page).fill("帮我做个贪吃蛇，支持触屏控制");
